CREATE TABLE AGENDAMENTO (
    ID                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    CONTA_ORIGEM_ID     UUID NOT NULL,
    CONTA_DESTINO_ID    UUID NOT NULL,
    VALOR_CENTAVOS      BIGINT NOT NULL,
    EXECUTAR_EM         TIMESTAMPTZ NOT NULL,
    ESTADO              VARCHAR(30) NOT NULL,
    TENTATIVAS          INTEGER NOT NULL DEFAULT 0,
    TRANSFERENCIA_ID    UUID
);

-- CLIENTE (entidade Usuario)
CREATE TABLE CLIENTE (
    ID      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    NAME    VARCHAR(255) NOT NULL,
    CPF     VARCHAR(30) NOT NULL
);

-- CONTA
CREATE TABLE CONTA (
    ID                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    NUMERO                  VARCHAR(30) NOT NULL,
    USUARIO_ID              UUID,
    SALDO_CENTAVOS          BIGINT NOT NULL,
    LIMITE_DIARIO_CENTAVOS  INTEGER NOT NULL,
    ESTADO                  VARCHAR(30) NOT NULL,
    VERSAO                  BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT FK_CONTA_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES CLIENTE (ID)
);

-- TRANSFERENCIA
CREATE TABLE TRANSFERENCIA (
    ID                          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    CONTA_ORIGEM_ID             UUID NOT NULL,
    CONTA_DESTINO_ID            UUID NOT NULL,
    VALOR_CENTAVOS              BIGINT NOT NULL,
    TAXA_CENTAVOS               INTEGER NOT NULL,
    ESTADO                      VARCHAR(30) NOT NULL,
    TRANSFERENCIA_ORIGINAL_ID   UUID,
    CRIADA_EM                   TIMESTAMPTZ NOT NULL,
    CONCLUIDA_EM                TIMESTAMPTZ,

    CONSTRAINT FK_TRANSFERENCIA_CONTA_ORIGEM FOREIGN KEY (CONTA_ORIGEM_ID) REFERENCES CONTA (ID),
    CONSTRAINT FK_TRANSFERENCIA_CONTA_DESTINO FOREIGN KEY (CONTA_DESTINO_ID) REFERENCES CONTA (ID),
    CONSTRAINT FK_TRANSFERENCIA_ORIGINAL FOREIGN KEY (TRANSFERENCIA_ORIGINAL_ID) REFERENCES TRANSFERENCIA (ID)
);

-- MOVIMENTO
CREATE SEQUENCE movimento_seq_gen START WITH 1 INCREMENT BY 1;

CREATE TABLE MOVIMENTO (
    ID                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    CONTA_ID                UUID NOT NULL,
    TRANSFERENCIA_ID        UUID,
    SEQUENCIA               BIGINT NOT NULL DEFAULT nextval('movimento_seq_gen'),
    TIPO_MOVIMENTO          VARCHAR(30) NOT NULL,
    VALOR_CENTAVOS          BIGINT NOT NULL,
    SALDO_APOS_CENTAVOS     BIGINT NOT NULL,
    CRIADO_EM               TIMESTAMPTZ NOT NULL,

    CONSTRAINT FK_MOVIMENTO_CONTA FOREIGN KEY (CONTA_ID) REFERENCES CONTA (ID),
    CONSTRAINT FK_MOVIMENTO_TRANSFERENCIA FOREIGN KEY (TRANSFERENCIA_ID) REFERENCES TRANSFERENCIA (ID)
);

-- IDEMPOTENCIA
CREATE TABLE IDEMPOTENCIA (
    CHAVE               VARCHAR(255) PRIMARY KEY,
    ENDPOINT            VARCHAR(255),
    HASH_REQUISICAO     VARCHAR(255) NOT NULL,
    RESPOSTA_JSON       TEXT NOT NULL,
    STATUS_HTTP         INTEGER NOT NULL,
    CRIADO_EM           TIMESTAMPTZ NOT NULL
);

