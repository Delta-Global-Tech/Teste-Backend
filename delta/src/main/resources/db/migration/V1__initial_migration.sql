ALTER TABLE AGENDAMENTO
    ADD CONSTRAINT FK_AGENDAMENTO_CONTA_ORIGEM FOREIGN KEY (CONTA_ORIGEM_ID) REFERENCES CONTA (ID),
    ADD CONSTRAINT FK_AGENDAMENTO_CONTA_DESTINO FOREIGN KEY (CONTA_DESTINO_ID) REFERENCES CONTA (ID),
    ADD CONSTRAINT FK_AGENDAMENTO_TRANSFERENCIA FOREIGN KEY (TRANSFERENCIA_ID) REFERENCES TRANSFERENCIA (ID);